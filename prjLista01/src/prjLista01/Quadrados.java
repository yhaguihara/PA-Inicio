package prjLista01;

public class Quadrados {
	public static void main(String[] args) {
		int a, b, c, quad1, quad2, quad3, soma; //Declaração de variáveis
		
		a = 2;
		b = 2;
		c = 2;
		quad1 = a*a;
		quad2 = b*b;
		quad3 = c*c;
		soma = quad1+quad2+quad3;
		System.out.println("A soma dos quadrados é: "+ soma);
		
		
	}
}
